async function seedPersons() {
  try {
    const db = await connectDB();
    const personsCollection = db.collection('persons');
    const personFundsCollection = db.collection('personFunds');
    const fundTypesCollection = db.collection('fundTypes');

    console.log("⏳ Fetching fund types...");
    // ফান্ড টাইপের আইডি খুঁজে বের করা
    const constructionFund = await fundTypesCollection.findOne({ name: 'নির্মাণ কাজ' });
    const annualFund = await fundTypesCollection.findOne({ name: 'বাৎসরিক চাঁদা' });

    if (!constructionFund || !annualFund) {
      console.error("❌ Fund types not found! Please run the initial fundTypes seed first.");
      process.exit(1);
    }

    const phone = "01718958840";
    let insertedCount = 0;

    console.log(`⏳ Inserting ${names.length} persons... This may take a moment.`);

    for (const name of names) {
      const trimmedName = name.trim();
      if (!trimmedName) continue;

      // ডুপ্লিকেট চেক (একই নাম ও ফোন নাম্বার থাকলে স্কিপ করবে)
      const existingPerson = await personsCollection.findOne({ name: trimmedName, phone });
      if (existingPerson) {
        console.log(`⚠️ Skipping duplicate: ${trimmedName}`);
        continue;
      }

      // ১. ব্যক্তি তৈরি করা
      const newPerson = {
        name: trimmedName,
        phone: phone,
        createdAt: new Date(),
      };

      const result = await personsCollection.insertOne(newPerson);
      const personId = result.insertedId;

      // ২. ফান্ড অ্যাসাইন করা
      const personFunds = [
        {
          personId: personId,
          fundTypeId: constructionFund._id,
          assignedAmount: 10000,
          createdAt: new Date(),
        },
        {
          personId: personId,
          fundTypeId: annualFund._id,
          assignedAmount: 1000,
          createdAt: new Date(),
        }
      ];

      await personFundsCollection.insertMany(personFunds);
      insertedCount++;
    }

    console.log(`✅ Successfully inserted ${insertedCount} persons with assigned funds!`);
    process.exit(0);
  } catch (error) {
    console.error("❌ Error seeding persons:", error);
    process.exit(1);
  }
}

seedPersons();